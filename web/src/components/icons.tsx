// Lightweight feather-style icon set (stroke, 24×24, round caps) so the UI can
// have iconography without pulling in an icon dependency. Each is a Chakra
// `Icon`, so `boxSize` / `color` props work as usual.
function make(path: ReactNode) {
  return function IconCmp(props: IconProps) {
    return (
      <Icon
        asChild={false}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={2}
        strokeLinecap="round"
        strokeLinejoin="round"
        {...props}
      >
        {path}
      </Icon>
    );
  };
}

